-- Generatoren voor de platformbestanden. Alleen in de testdatabase gebruiken; niet in een klantdatabase.
create schema if not exists platform_tools;
revoke all on schema platform_tools from public, anon, authenticated;

create or replace function platform_tools.schema_ddl(p_schema text, p_as text default null)
returns text language plpgsql stable security definer set search_path = '' as $f$
declare
  s text := p_schema; t text := coalesce(p_as, p_schema);
  out text := ''; r record; cols text;
  qs text := quote_ident(s); qt text := quote_ident(t);
begin
  out := out || format(E'-- Schema %s (bron: %s), gegenereerd %s\nset check_function_bodies = off;\ncreate schema if not exists %s;\n\n', t, s, now()::date, qt);
  for r in select c.relname, sq.* from pg_class c join pg_namespace n on n.oid=c.relnamespace join pg_sequence sq on sq.seqrelid=c.oid
           where n.nspname=s and c.relkind='S' and not exists (select 1 from pg_depend d where d.objid=c.oid and d.deptype='i') order by c.relname loop
    out := out || format(E'create sequence if not exists %s.%I start %s increment %s;\n', qt, r.relname, r.seqstart, r.seqincrement);
  end loop;
  for r in select p.oid from pg_proc p join pg_namespace n on n.oid=p.pronamespace
           where n.nspname=s and p.prokind in ('f','p') and not exists (select 1 from pg_depend d where d.objid=p.oid and d.deptype='e') order by p.proname, p.oid loop
    out := out || replace(pg_get_functiondef(r.oid), 'FUNCTION '||qs||'.', 'FUNCTION '||qt||'.') || E';\n\n';
  end loop;
  for r in select c.oid, c.relname from pg_class c join pg_namespace n on n.oid=c.relnamespace where n.nspname=s and c.relkind in ('r','p') order by c.relname loop
    select string_agg(format('  %I %s%s%s%s', a.attname, format_type(a.atttypid,a.atttypmod),
             case when a.attidentity='a' then ' generated always as identity' when a.attidentity='d' then ' generated by default as identity' else '' end,
             case when a.attgenerated='s' then ' generated always as ('||pg_get_expr(ad.adbin,ad.adrelid)||') stored'
                  when ad.adbin is not null and a.attidentity='' then ' default '||pg_get_expr(ad.adbin,ad.adrelid) else '' end,
             case when a.attnotnull then ' not null' else '' end), E',\n' order by a.attnum)
      into cols
      from pg_attribute a left join pg_attrdef ad on ad.adrelid=a.attrelid and ad.adnum=a.attnum
      where a.attrelid=r.oid and a.attnum>0 and not a.attisdropped;
    out := out || format(E'create table if not exists %s.%I (\n%s\n);\n', qt, r.relname, cols);
  end loop;
  out := out || E'\n';
  for r in select c.relname, co.conname, pg_get_constraintdef(co.oid) def, co.contype
           from pg_constraint co join pg_class c on c.oid=co.conrelid join pg_namespace n on n.oid=c.relnamespace
           where n.nspname=s and co.contype in ('p','u','c','x','f')
           order by case co.contype when 'p' then 1 when 'u' then 2 when 'x' then 3 when 'c' then 4 else 5 end, c.relname, co.conname loop
    out := out || format(E'alter table %s.%I add constraint %I %s;\n', qt, r.relname, r.conname, replace(r.def, ' '||qs||'.', ' '||qt||'.'));
  end loop;
  out := out || E'\n';
  for r in select pg_get_indexdef(i.indexrelid) def from pg_index i join pg_class c on c.oid=i.indexrelid join pg_namespace n on n.oid=c.relnamespace
           where n.nspname=s and not exists (select 1 from pg_constraint co where co.conindid=i.indexrelid) order by c.relname loop
    out := out || replace(r.def, ' ON '||qs||'.', ' ON '||qt||'.') || E';\n';
  end loop;
  out := out || E'\n';
  for r in select c.relname, pg_get_viewdef(c.oid) def from pg_class c join pg_namespace n on n.oid=c.relnamespace where n.nspname=s and c.relkind='v' order by c.relname loop
    out := out || format(E'create or replace view %s.%I as %s\n', qt, r.relname, replace(r.def, qs||'.', qt||'.'));
  end loop;
  for r in select pg_get_triggerdef(tg.oid) def from pg_trigger tg join pg_class c on c.oid=tg.tgrelid join pg_namespace n on n.oid=c.relnamespace
           where n.nspname=s and not tg.tgisinternal order by c.relname, tg.tgname loop
    out := out || replace(replace(r.def, ' ON '||qs||'.', ' ON '||qt||'.'), 'FUNCTION '||qs||'.', 'FUNCTION '||qt||'.') || E';\n';
  end loop;
  out := out || E'\n';
  for r in select c.relname from pg_class c join pg_namespace n on n.oid=c.relnamespace where n.nspname=s and c.relkind in ('r','p') and c.relrowsecurity order by c.relname loop
    out := out || format(E'alter table %s.%I enable row level security;\n', qt, r.relname);
  end loop;
  for r in select * from pg_policies where schemaname=s order by tablename, policyname loop
    out := out || format(E'create policy %I on %s.%I as %s for %s to %s%s%s;\n', r.policyname, qt, r.tablename, r.permissive, r.cmd,
      array_to_string(r.roles, ', '), coalesce(' using ('||r.qual||')',''), coalesce(' with check ('||r.with_check||')',''));
  end loop;
  out := out || E'\n';
  out := out || format(E'revoke all on all tables in schema %s from anon, authenticated;\nrevoke all on all functions in schema %s from public, anon, authenticated;\n', qt, qt);
  for r in select c.relname, g.privilege_type, g.grantee from information_schema.role_table_grants g join pg_class c on c.relname=g.table_name join pg_namespace n on n.oid=c.relnamespace and n.nspname=g.table_schema
           where g.table_schema=s and g.grantee in ('anon','authenticated','service_role') order by 1,3,2 loop
    out := out || format(E'grant %s on %s.%I to %I;\n', r.privilege_type, qt, r.relname, r.grantee);
  end loop;
  for r in select p.oid, p.proname, pg_get_function_identity_arguments(p.oid) args, a.grantee::regrole::text grantee
           from pg_proc p join pg_namespace n on n.oid=p.pronamespace, aclexplode(coalesce(p.proacl, acldefault('f', p.proowner))) a
           where n.nspname=s and a.privilege_type='EXECUTE' and a.grantee<>0 and a.grantee::regrole::text in ('anon','authenticated','service_role')
             and not exists (select 1 from pg_depend d where d.objid=p.oid and d.deptype='e') order by 2,4 loop
    out := out || format(E'grant execute on function %s.%I(%s) to %I;\n', qt, r.proname, r.args, r.grantee);
  end loop;
  if t <> 'public' then out := out || format(E'grant usage on schema %s to anon, authenticated, service_role;\n', qt); end if;
  return out;
end $f$;
revoke all on function platform_tools.schema_ddl(text, text) from public, anon, authenticated;

create or replace function platform_tools.bootstrap_sql()
returns text language plpgsql stable security definer set search_path = '' as $f$
declare out text := ''; r record; js jsonb; keys text;
begin
  out := E'-- Opstartgedeelte voor een nieuwe klantdatabase: extensies, opslag, startinstellingen, hoofdvestiging en geplande taken.\n'
      || E'-- Vul de {{...}}-waarden in (zie PLATFORM-NIEUWE-KLANT.md) en draai dit NA 0001_schema_public.sql.\n\n'
      || E'create extension if not exists pgcrypto with schema extensions;\ncreate extension if not exists "uuid-ossp" with schema extensions;\ncreate extension if not exists pg_net;\ncreate extension if not exists pg_cron;\n\n';
  out := out || E'-- Opslagmappen\n';
  for r in select * from storage.buckets order by id loop
    out := out || format(E'insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types) values (%L, %L, %s, %s, %s) on conflict (id) do nothing;\n',
      r.id, r.name, case when r.public then 'true' else 'false' end, coalesce(r.file_size_limit::text,'null'), coalesce(quote_literal(r.allowed_mime_types::text)||'::text[]','null'));
  end loop;
  for r in select * from pg_policies where schemaname='storage' order by tablename, policyname loop
    out := out || format(E'create policy %I on storage.%I as %s for %s to %s%s%s;\n', r.policyname, r.tablename, r.permissive, r.cmd,
      array_to_string(r.roles, ', '), coalesce(' using ('||r.qual||')',''), coalesce(' with check ('||r.with_check||')',''));
  end loop;
  out := out || E'\n-- Startinstellingen (één rij per tabel; geheimen leeg, extra''s uit)\n';
  for r in select unnest(array['shop_settings','mtf_promotion_settings','mtf_game_settings','mtf_home_settings','mtf_campaign_controls','mtf_opening_hours']) t loop
    for js in execute format('select to_jsonb(x) from public.%I x', r.t) loop
      js := js - 'updated_at' - 'updated_by' - 'created_at';
      if r.t = 'mtf_promotion_settings' then js := js || jsonb_build_object('google_api_key','','google_place_id','','enabled',false,'product_id',null); end if;
      if r.t = 'shop_settings' then js := js || jsonb_build_object('is_open', false); end if;
      if r.t = 'mtf_game_settings' then js := js || jsonb_build_object('visible', false, 'title', 'Game'); end if;
      if r.t = 'mtf_campaign_controls' then js := js || jsonb_build_object('visible', false, 'enabled', false); end if;
      if r.t = 'mtf_home_settings' and js ? 'favorites_since' then js := js - 'favorites_since'; end if;
      select string_agg(quote_ident(k), ', ' order by k) into keys from jsonb_object_keys(js) k;
      out := out || format(E'insert into public.%I (%s) select %s from jsonb_populate_record(null::public.%I, %L::jsonb) on conflict do nothing;\n', r.t, keys, keys, r.t, js::text);
    end loop;
  end loop;
  out := out || E'\n-- Hoofdvestiging\n'
      || E'insert into public.mtf_locations (slug, schema_name, name, address, order_email, published, mailbox_ready, is_primary, features, order_prefix, order_pad, order_max)\n'
      || E'values (''{{SLUG}}'', ''public'', ''{{NAAM}}'', ''{{ADRES}}'', ''{{ORDERMAIL}}'', false, false, true, ''{}'', ''{{BESTELNUMMER_VOORVOEGSEL}}'', 5, null)\n'
      || E'on conflict (slug) do nothing;\n';
  out := out || E'\n-- Geplande taken (de service-sleutel staat in de kluis als mtf_service_role_key)\n'
      || E'select vault.create_secret(''{{SERVICE_ROLE_KEY}}'', ''mtf_service_role_key'') where not exists (select 1 from vault.secrets where name = ''mtf_service_role_key'');\n';
  for r in select * from (values ('mtf-send-order-emails','* * * * *','dynamic-handler','{"limit":10}'),('mtf-portal-mail-retry','*/2 * * * *','portal-mail-worker','{}'),('mtf-review-mails','*/5 * * * *','review-mail-worker','{}')) v(job,sched,fn,body) loop
    out := out || format(E'select cron.schedule(%L, %L, $c$select net.http_post(url := ''{{SUPABASE_URL}}/functions/v1/%s'', headers := jsonb_build_object(''Content-Type'',''application/json'',''Authorization'',''Bearer '' || (select decrypted_secret from vault.decrypted_secrets where name = ''mtf_service_role_key'' limit 1)), body := ''%s''::jsonb);$c$);\n', r.job, r.sched, r.fn, r.body);
  end loop;
  return out;
end $f$;
revoke all on function platform_tools.bootstrap_sql() from public, anon, authenticated;
